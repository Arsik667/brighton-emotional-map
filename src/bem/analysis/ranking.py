"""
Честное ранжирование объектов с разным числом наблюдений.

=== ПРОБЛЕМА ===
Заведение с тремя восторженными отзывами получает оценку 1.00.
Заведение с двумястами отзывами, из которых 85% хороших, получает 0.70.
Сортировка по средней ставит первое выше. Но мы же понимаем, что второе
надёжнее: три отзыва могли написать друзья владельца, а могло просто
повезти. Это не гипотетическая придирка - именно так ломаются рейтинги
в реальных продуктах.

=== РЕШЕНИЕ: СЖАТИЕ К СРЕДНЕМУ (shrinkage) ===
Идея простая. Пока наблюдений мало, мы почти ничего не знаем о месте -
и разумнее предполагать, что оно среднее. Чем больше наблюдений, тем
сильнее мы верим самим данным, а не предположению.

Формула:

    оценка = (n * своя_оценка + k * общее_среднее) / (n + k)

где k - "сила предположения", выраженная в количестве наблюдений.
При k=10 заведение с 10 отзывами получит оценку ровно посередине между
своей и общегородской; с сотней отзывов - почти свою собственную.

По сути мы добавляем каждому месту k воображаемых средних отзывов.
Тот же приём под названием "байесовское среднее" использует IMDb в
своём топ-250 - иначе фильм с семью оценками по 10 баллов возглавлял бы
список вечно.

Как выбирать k: это компромисс. Большое k = консервативный рейтинг,
малое = шумный. Разумная отправная точка - медианное число наблюдений
на объект.
"""

from __future__ import annotations

import numpy as np
import pandas as pd


def shrunk_score(
    values: pd.Series,
    counts: pd.Series,
    prior: float | None = None,
    strength: float | None = None,
) -> pd.Series:
    """
    Сжать оценки к общему среднему пропорционально числу наблюдений.

    values   - своя оценка каждого объекта
    counts   - сколько наблюдений у каждого объекта
    prior    - к чему сжимаем (по умолчанию - взвешенное среднее по всем)
    strength - k, сила сжатия (по умолчанию - медиана counts)
    """
    if prior is None:
        # Взвешенное среднее: объект с двумястами отзывами должен влиять
        # на общегородскую планку сильнее, чем объект с тремя.
        prior = float(np.average(values, weights=counts))

    if strength is None:
        strength = float(max(counts.median(), 1))

    return (counts * values + strength * prior) / (counts + strength)


def rank_places(
    stats: pd.DataFrame,
    value_col: str = "net_sentiment",
    count_col: str = "n_texts",
    min_count: int = 3,
    strength: float | None = None,
) -> pd.DataFrame:
    """
    Добавить сжатую оценку и отсортировать по ней.

    Возвращает таблицу с колонками:
        <value_col>_shrunk - оценка, пригодная для сортировки
        confidence         - насколько мы доверяем именно своим данным
                             объекта, от 0 (только предположение) до 1
    """
    df = stats[stats[count_col] >= min_count].copy()

    if df.empty:
        return df

    if strength is None:
        strength = float(max(df[count_col].median(), 1))

    prior = float(np.average(df[value_col], weights=df[count_col]))

    df[f"{value_col}_shrunk"] = shrunk_score(
        df[value_col], df[count_col], prior=prior, strength=strength
    )
    # Доля собственного веса объекта в итоговой оценке.
    # Удобно показывать рядом: сразу видно, где цифре можно верить.
    df["confidence"] = df[count_col] / (df[count_col] + strength)

    return df.sort_values(f"{value_col}_shrunk", ascending=False)
